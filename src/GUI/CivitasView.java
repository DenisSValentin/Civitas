    @Override
    public void actualiza() {
        jugadorPanel1.setJugador(juego.getJugadorActual());
        casillaActual.setText(juego.getTablero().getCasilla(juego.getJugadorActual().getCasillaActual()).toString());
        labelRanking.setVisible(false);
        ScrollPanel.setVisible(false);
        textRanking.setVisible(false);
        
        if(juego.finalDelJuego()){
            labelRanking.setVisible(true);
            ScrollPanel.setVisible(true);
            textRanking.setVisible(true);
            
            juego.ranking();
            String cadena = juego.getJugadores().get(0).getNombre() + "\n" + juego.getJugadores().get(1).getNombre() + "\n" +
                    juego.getJugadores().get(2).getNombre() +"\n" + juego.getJugadores().get(3).getNombre();
            
            textRanking.setText(cadena);
        }
        
        repaint();
        revalidate();
    }

    @Override
    public void pausa() {
        int val= JOptionPane.showConfirmDialog(null, "¿Continuar?", 
        "Siguiente paso", JOptionPane.YES_NO_OPTION);
        if (val==1) System.exit(0);
    }

    @Override
    public Respuesta comprar() {
        int opcion= 1-JOptionPane.showConfirmDialog(null, "¿Quieres comprar la calle actual?", "Compra", JOptionPane.YES_NO_OPTION);
        if(opcion == 0)
            return Respuesta.NO;
        else
            return Respuesta.SI;
    }

    @Override
    public OperacionInmobiliaria elegirOperacion() {
        GestionarDialog gD = new GestionarDialog(this);
        int aux = gD.getGestion();
        
        OperacionInmobiliaria op;
        
        if(aux == 0)
            op = OperacionInmobiliaria.CONSTRUIR_CASA;
        else if(aux == 1)
            op = OperacionInmobiliaria.CONSTRUIR_HOTEL;
        else
            op = OperacionInmobiliaria.TERMINAR;
        
        return op;
    }

    @Override
    public int elegirPropiedad() {
        PropiedadDialog pD = new PropiedadDialog(this, juego.getJugadorActual());
        
        return pD.getPropiedadElegida();
    }

    @Override
    public void mostrarSiguienteOperacion(OperacionJuego operación) {
        
        sigOperacion.setText(operación.toString());
        
        if(operación == OperacionJuego.AVANZAR){
            Dado.createInstance(this);
        }
        
        repaint();
    }

    @Override
    public void mostrarEventos() {
        if (!Diario.getInstance().getEventos().isEmpty())
            new DiarioDialog(this); //crea la ventana del  diario
    }
    
